#!/bin/bash
# esp-color-detector — Certificate Generator
# ========================================
# Generates a self-signed certificate + key for the ESP32 HTTPS server.
# Certificate is valid for ~10 years, CN=192.168.4.1, SAN for 192.168.4.1 and colors.local
# Output: src/certs.h (embedded in firmware)

set -e

OUT_DIR="$(dirname "$0")/../src"
CERT_FILE="$OUT_DIR/cert.pem"
KEY_FILE="$OUT_DIR/key.pem"
HEADER_FILE="$OUT_DIR/certs.h"

echo "Generating self-signed certificate for ESP32 HTTPS server..."
echo "  CN: 192.168.4.1"
echo "  SAN: 192.168.4.1, colors.local"
echo "  Validity: ~10 years (3650 days)"
echo ""

# Generate private key (EC P-256 for smaller size)
openssl ecparam -genkey -name prime256v1 -out "$KEY_FILE"

# Generate self-signed certificate
openssl req -new -x509 -key "$KEY_FILE" -out "$CERT_FILE" -days 3650 \
  -subj "/CN=192.168.4.1" \
  -addext "subjectAltName=IP:192.168.4.1,DNS:colors.local"

echo ""
echo "Certificate generated:"
openssl x509 -in "$CERT_FILE" -noout -subject -dates -ext subjectAltName

# Convert to C header
echo "" > "$HEADER_FILE"
cat >> "$HEADER_FILE" <<'EOF'
/*
 * esp-color-detector — TLS Certificate & Private Key
 * ==================================================
 * AUTO-GENERATED by tools/gen_cert.sh — DO NOT EDIT BY HAND.
 * Regenerate with: bash tools/gen_cert.sh
 *
 * Self-signed ECDSA P-256 certificate, valid ~10 years.
 * CN: 192.168.4.1
 * SAN: IP:192.168.4.1, DNS:colors.local
 */

#pragma once
#include <Arduino.h>

static const char SERVER_CERT[] PROGMEM = R"EOF(
EOF

# Append certificate (PEM format, escaped for C string)
sed 's/$/\\n/' "$CERT_FILE" | tr -d '\n' >> "$HEADER_FILE"
cat >> "$HEADER_FILE" <<'EOF'
)EOF";

static const char SERVER_KEY[] PROGMEM = R"EOF(
EOF

# Append private key
sed 's/$/\\n/' "$KEY_FILE" | tr -d '\n' >> "$HEADER_FILE"
cat >> "$HEADER_FILE" <<'EOF'
)EOF";

static const size_t SERVER_CERT_LEN = sizeof(SERVER_CERT) - 1;
static const size_t SERVER_KEY_LEN  = sizeof(SERVER_KEY) - 1;
EOF

echo ""
echo "Header written to: $HEADER_FILE"
echo ""
echo "To use in Arduino-ESP32 HTTPS server:"
echo "  httpd_ssl_config_t conf = HTTPD_SSL_CONFIG_DEFAULT();"
echo "  conf.servercert = SERVER_CERT;"
echo "  conf.servercert_len = SERVER_CERT_LEN;"
echo "  conf.prvtkey_pem = SERVER_KEY;"
echo "  conf.prvtkey_len = SERVER_KEY_LEN;"